package main

import (
	"fmt"
	"strings"
	"testing"
)

// agentsTS builds a small src/agents.ts: the consts and helpers in head,
// then the agents table.
func agentsTS(head string, entries ...string) string {
	return "const home = homedir();\nconst configHome = xdgConfig ?? join(home, '.config');\n" + head +
		"\nexport const agents: Record<AgentType, AgentConfig> = {\n" + strings.Join(entries, "") + "};\n"
}

func agent(id, skillsDir, global, detect string) string {
	name := strings.Trim(id, "'")
	return fmt.Sprintf("  %s: {\n    name: '%s',\n    displayName: '%s',\n    skillsDir: '%s',\n    globalSkillsDir: %s,\n"+
		"    detectInstalled: async () => {\n      return %s;\n    },\n  },\n", id, name, strings.ToUpper(name[:1])+name[1:], skillsDir, global, detect)
}

// pick is a helper in the shape of getOpenClawGlobalSkillsDir: the skills
// folder in the first of dirs that exists, or else fallback's.
func pick(name string, dirs ...string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "export function get%sGlobalSkillsDir(\n  homeDir = home,\n  pathExists: (path: string) => boolean = existsSync\n) {\n", name)
	for _, d := range dirs[:len(dirs)-1] {
		fmt.Fprintf(&b, "  if (pathExists(join(homeDir, '%s'))) {\n    return join(homeDir, '%s/skills');\n  }\n", d, d)
	}
	fmt.Fprintf(&b, "  return join(homeDir, '%s/skills');\n}\n", dirs[len(dirs)-1])
	return b.String()
}

// file is the skill_agents.go generate should write for these rows.
func file(rows ...string) string {
	return "// Code generated by genagents from vercel-labs/skills v0.0.1 src/agents.ts. DO NOT EDIT.\n\npackage provider\n\nvar skillAgents = []skillAgent{\n\t" +
		strings.Join(rows, ",\n\t") + ",\n}\n"
}

func TestGenerate(t *testing.T) {
	tests := []struct {
		id, src, want, err string
	}{
		{
			id:   "an agent whose project folder is .agents/skills is universal, so it reads the shared folder too",
			src:  agentsTS("", agent("aspen", ".agents/skills", "join(home, '.aspen/skills')", "existsSync(join(home, '.aspen'))")),
			want: file(`{Name: "aspen", Display: "Aspen", Dirs: []string{"~/.aspen/skills"}, Detect: []string{"~/.aspen"}, Universal: true}`),
		},
		{
			id:   "a folder picked at run time lists every choice, as OpenClaw's does",
			src:  agentsTS(pick("Pincer", ".pincer", ".clawpincer", ".pincer"), agent("pincer", "skills", "getPincerGlobalSkillsDir()", "existsSync(join(home, '.pincer'))")),
			want: file(`{Name: "pincer", Display: "Pincer", Dirs: []string{"~/.pincer/skills", "~/.clawpincer/skills"}, Detect: []string{"~/.pincer"}}`),
		},
		{
			id:   "a helper with one folder to pick gives that folder",
			src:  agentsTS(pick("Reed", ".reed"), agent("reed", "skills", "getReedGlobalSkillsDir()", "existsSync(join(home, '.reed'))")),
			want: file(`{Name: "reed", Display: "Reed", Dirs: []string{"~/.reed/skills"}, Detect: []string{"~/.reed"}}`),
		},
		{
			id:  "a folder picked some other way fails",
			src: agentsTS(pick("Quill", ".quill", ".oldquill", ".newquill"), agent("quill", "skills", "getQuillGlobalSkillsDir()", "existsSync(join(home, '.quill'))")),
			err: "getQuillGlobalSkillsDir: must return the first folder whose parent exists, or else the first",
		},
		{
			id:  "a path on a base the generator doesn't know fails, naming it",
			src: agentsTS("", agent("gale", ".gale/skills", "join(home, '.gale/skills')", "existsSync(join(galeHome, 'gale'))")),
			err: "gale: unknown base galeHome in join(galeHome, 'gale')",
		},
		{
			id:  "so does a skills folder on one",
			src: agentsTS("", agent("mist", ".mist/skills", "join(mistHome, 'skills')", "existsSync(join(home, '.mist'))")),
			err: "mist: unknown base mistHome in join(mistHome, 'skills')",
		},
		{
			id: "the Windows and Flatpak bases are left out on purpose",
			src: agentsTS("const zedAppDataHome = process.env.APPDATA?.trim();\nconst zedFlatpakConfigHome = process.env.FLATPAK_XDG_CONFIG_HOME?.trim();\n",
				agent("haze", ".agents/skills", "join(home, '.agents/skills')", "existsSync(join(configHome, 'haze')) ||\n"+
					"        (!!zedAppDataHome && existsSync(join(zedAppDataHome, 'Haze'))) ||\n"+
					"        (!!zedFlatpakConfigHome && existsSync(join(zedFlatpakConfigHome, 'haze')))")),
			want: file(`{Name: "haze", Display: "Haze", Dirs: []string{"~/.agents/skills"}, Detect: []string{"${XDG_CONFIG_HOME:-~/.config}/haze"}, Universal: true}`),
		},
		{
			id:   "an agent with its own folder under home",
			src:  agentsTS("", agent("alder", ".alder/skills", "join(home, '.alder/skills')", "existsSync(join(home, '.alder'))")),
			want: file(`{Name: "alder", Display: "Alder", Dirs: []string{"~/.alder/skills"}, Detect: []string{"~/.alder"}}`),
		},
		{
			id: "an env setting moves the folder",
			src: agentsTS("const brookHome = process.env.BROOK_HOME?.trim() || join(home, '.brook');\n",
				agent("brook", ".brook/skills", "join(brookHome, 'skills')", "existsSync(brookHome)")),
			want: file(`{Name: "brook", Display: "Brook", Dirs: []string{"${BROOK_HOME:-~/.brook}/skills"}, Detect: []string{"${BROOK_HOME:-~/.brook}"}}`),
		},
		{
			id: "an is*Installed helper lends its paths",
			src: agentsTS("export function isCedarInstalled(\n  homeDir = home,\n  pathExists: (path: string) => boolean = existsSync\n) {\n"+
				"  return pathExists(join(homeDir, '.cedar')) || pathExists('/Applications/Cedar.app');\n}\n",
				agent("cedar", ".cedar/skills", "join(home, '.cedar/skills')", "isCedarInstalled()")),
			want: file(`{Name: "cedar", Display: "Cedar", Dirs: []string{"~/.cedar/skills"}, Detect: []string{"~/.cedar", "/Applications/Cedar.app"}}`),
		},
		{
			id:   "join takes several parts, and configHome follows XDG",
			src:  agentsTS("", agent("'dune-cli'", ".dune/skills", "join(configHome, 'dune', 'skills')", "existsSync(join(configHome, 'dune'))")),
			want: file(`{Name: "dune-cli", Display: "Dune-cli", Dirs: []string{"${XDG_CONFIG_HOME:-~/.config}/dune/skills"}, Detect: []string{"${XDG_CONFIG_HOME:-~/.config}/dune"}}`),
		},
		{
			id: "project paths, agents with no global folder, and the universal entry are left out",
			src: agentsTS("",
				agent("elm", ".elm/skills", "join(home, '.elm/skills')", "existsSync(join(process.cwd(), '.elm'))"),
				agent("fern", "fern/skills", "undefined", "false"),
				agent("universal", ".agents/skills", "join(configHome, 'agents/skills')", "false")),
			want: file(`{Name: "elm", Display: "Elm", Dirs: []string{"~/.elm/skills"}, Detect: []string{}}`),
		},
	}
	for _, tt := range tests {
		t.Run(tt.id, func(t *testing.T) {
			out, err := generate(tt.src, "v0.0.1")
			gotErr := ""
			if err != nil {
				gotErr = err.Error()
			}
			if string(out) != tt.want || gotErr != tt.err {
				t.Errorf("got\n%s%q\nwant\n%s%q", out, gotErr, tt.want, tt.err)
			}
		})
	}
}
